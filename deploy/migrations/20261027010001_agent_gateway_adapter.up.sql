-- Gramsrv owns only the durable Telegram/Gateway transport boundary. Gateway
-- owns Agent profiles, tasks, approvals, runs and their event history.
CREATE SEQUENCE agent_gateway_update_id_seq AS bigint;

CREATE TABLE agent_gateway_inbound (
    update_id bigint PRIMARY KEY DEFAULT nextval('agent_gateway_update_id_seq'),
    kind text NOT NULL CHECK (kind IN ('message', 'group_message', 'callback')),
    bot_api_update_id bigint,
    callback_query_id bigint,
    owner_user_id bigint NOT NULL,
    telegram_actor_user_id bigint NOT NULL,
    chat_bot_id bigint NOT NULL,
    telegram_chat_id bigint NOT NULL,
    telegram_message_id integer NOT NULL,
    telegram_reply_to_message_id integer NOT NULL DEFAULT 0 CHECK (telegram_reply_to_message_id >= 0),
    telegram_top_message_id integer NOT NULL DEFAULT 0 CHECK (telegram_top_message_id >= 0),
    callback_data bytea,
    payload jsonb NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'dispatching', 'accepted', 'failed')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_owner text NOT NULL DEFAULT '',
    lease_until timestamptz,
    gateway_inbound_id text,
    gateway_profile_id text,
    gateway_task_id text,
    disposition text NOT NULL DEFAULT '',
    callback_answer jsonb,
    last_error text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (gateway_inbound_id),
    CHECK ((kind = 'message' AND bot_api_update_id IS NULL AND callback_query_id IS NULL AND callback_data IS NULL)
        OR (kind = 'group_message' AND callback_query_id IS NULL AND callback_data IS NULL)
        OR (kind = 'callback' AND bot_api_update_id IS NULL AND callback_query_id IS NOT NULL AND callback_data IS NOT NULL)),
    CHECK ((status = 'dispatching' AND lease_owner <> '' AND lease_until IS NOT NULL)
        OR (status <> 'dispatching' AND lease_owner = '' AND lease_until IS NULL))
);
CREATE UNIQUE INDEX agent_gateway_inbound_callback_query_idx
    ON agent_gateway_inbound(chat_bot_id, callback_query_id) WHERE callback_query_id IS NOT NULL;
CREATE UNIQUE INDEX agent_gateway_group_bot_update_idx
    ON agent_gateway_inbound(chat_bot_id, bot_api_update_id) WHERE bot_api_update_id IS NOT NULL;
CREATE UNIQUE INDEX agent_gateway_group_source_message_idx
    ON agent_gateway_inbound(chat_bot_id, telegram_chat_id, telegram_message_id)
    WHERE kind = 'group_message';
CREATE UNIQUE INDEX agent_gateway_inbound_callback_action_idx
    ON agent_gateway_inbound(chat_bot_id, owner_user_id, telegram_chat_id, telegram_message_id, callback_data)
    WHERE kind = 'callback';
CREATE INDEX agent_gateway_inbound_due_idx
    ON agent_gateway_inbound(next_attempt_at, update_id)
    WHERE status IN ('pending', 'dispatching');

CREATE TABLE agent_gateway_delivery_receipts (
    receipt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway_id text NOT NULL,
    idempotency_key text NOT NULL,
    request_hash bytea NOT NULL CHECK (octet_length(request_hash) = 32),
    gateway_inbound_id text NOT NULL REFERENCES agent_gateway_inbound(gateway_inbound_id),
    purpose text NOT NULL CHECK (purpose IN ('setup', 'profile_welcome', 'task_update', 'group_task_update', 'owner_approval')),
    operation text NOT NULL CHECK (operation IN ('send', 'edit')),
    telegram_owner_user_id bigint NOT NULL,
    reply_to_update_id bigint NOT NULL,
    gateway_profile_id text,
    gateway_task_id text,
    telegram_message_id integer,
    text text NOT NULL,
    inline_keyboard jsonb,
    request_body jsonb NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'dispatching', 'delivered', 'failed')),
    result_telegram_message_id integer,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_owner text NOT NULL DEFAULT '',
    lease_until timestamptz,
    last_error text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (gateway_id, idempotency_key),
    CHECK ((purpose = 'setup' AND gateway_profile_id IS NULL AND gateway_task_id IS NULL AND operation = 'send')
        OR (purpose = 'profile_welcome' AND gateway_profile_id IS NOT NULL AND gateway_task_id IS NULL AND operation = 'send')
        OR (purpose = 'task_update' AND gateway_profile_id IS NULL AND gateway_task_id IS NOT NULL)
        OR (purpose = 'group_task_update')
        OR (purpose = 'owner_approval' AND gateway_profile_id IS NOT NULL AND gateway_task_id IS NOT NULL AND operation = 'send')),
    CHECK ((operation = 'send' AND telegram_message_id IS NULL)
        OR (operation = 'edit' AND telegram_message_id > 0)),
    CHECK ((status = 'dispatching' AND lease_owner <> '' AND lease_until IS NOT NULL)
        OR (status <> 'dispatching' AND lease_owner = '' AND lease_until IS NULL))
);
CREATE UNIQUE INDEX agent_gateway_task_first_message_idx
    ON agent_gateway_delivery_receipts(gateway_id, gateway_task_id, telegram_owner_user_id)
    WHERE purpose = 'task_update' AND operation = 'send';
CREATE UNIQUE INDEX agent_gateway_group_task_first_message_idx
    ON agent_gateway_delivery_receipts(gateway_id, gateway_task_id, telegram_owner_user_id)
    WHERE purpose = 'group_task_update' AND gateway_task_id IS NOT NULL AND operation = 'send';
CREATE UNIQUE INDEX agent_gateway_owner_approval_idx
    ON agent_gateway_delivery_receipts(gateway_id, gateway_task_id, telegram_owner_user_id)
    WHERE purpose = 'owner_approval' AND operation = 'send';
CREATE UNIQUE INDEX agent_gateway_setup_send_idx
    ON agent_gateway_delivery_receipts(gateway_id, gateway_inbound_id)
    WHERE purpose = 'setup' AND operation = 'send';
CREATE UNIQUE INDEX agent_gateway_profile_welcome_send_idx
    ON agent_gateway_delivery_receipts(gateway_id, gateway_inbound_id)
    WHERE purpose = 'profile_welcome' AND operation = 'send';
CREATE INDEX agent_gateway_delivery_due_idx
    ON agent_gateway_delivery_receipts(next_attempt_at, receipt_id)
    WHERE status IN ('pending', 'dispatching');

CREATE TABLE agent_gateway_request_nonces (
    gateway_id text NOT NULL,
    key_id text NOT NULL,
    nonce text NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (gateway_id, key_id, nonce)
);
CREATE INDEX agent_gateway_request_nonce_expiry_idx ON agent_gateway_request_nonces(expires_at);

COMMENT ON TABLE agent_gateway_inbound IS 'Durable Gramsrv-to-Gateway message/callback ingress and accepted handle binding; task state remains in Gateway.';
COMMENT ON TABLE agent_gateway_delivery_receipts IS 'Idempotent Gateway-to-Gramsrv Telegram send/edit receipt and delivery queue.';
